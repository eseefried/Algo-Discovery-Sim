"""Turn judged runs into shareable research artifacts under `skills/<domain>/learnings/`.

One Markdown file per judged run, plus a per-domain INDEX.md that aggregates across runs. The
interesting column is the rubric breakdown: which components of a paper's method the agents
recovered and which they consistently miss. That is the finding the benchmark exists to
produce, and it is what a collaborator can read without rerunning anything.

**These artifacts are evaluator-side.** They quote the sealed rubric and name the paper's
method, so nothing here may ever reach a prompt. Only `SKILL.md` is read when briefing agents
(see a2m/domains/profiles.py); `tests/test_skills.py` pins that separation.
"""

from __future__ import annotations

import json
from collections import defaultdict
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from a2m import skills
from a2m.tasks import load_card, load_vault

HEADER = "<!-- generated by `a2m learn`; evaluator-side, never shown to agents -->"


def _read(path: Path) -> Any:
    return json.loads(path.read_text()) if path.is_file() else None


def _events(run_dir: Path) -> list[dict]:
    out = []
    for path in [run_dir / "events.jsonl", *sorted(run_dir.glob("colonies/*/events.jsonl"))]:
        if path.is_file():
            out += [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return out


def _family_fates(events: list[dict], candidates: list[dict]) -> dict[str, dict]:
    """What happened to each method family the run tried."""
    fates: dict[str, dict] = defaultdict(
        lambda: {"candidates": 0, "best_gap": 1.0, "ready": False, "diagnoses": []})
    for c in candidates:
        f = fates[c.get("family", "?")]
        f["candidates"] += 1
        if c.get("results"):
            f["best_gap"] = min(f["best_gap"], float(c.get("gap", 1.0)))
        f["ready"] = f["ready"] or c.get("status") == "ready"
    for e in events:
        if e.get("kind") == "family_stalled" and e.get("family") in fates:
            fates[e["family"]]["diagnoses"].append("stalled")
        if e.get("kind") == "simulate" and e.get("error"):
            fates[e.get("family", "?")]["diagnoses"].append(e["error"][:120])
    return dict(fates)


def distill(run_dir: str | Path) -> Path:
    """Write one artifact for a judged run and refresh its domain index."""
    run_dir = Path(run_dir).resolve()
    submission = _read(run_dir / "submission.json")
    judge = _read(run_dir / "judge.json")
    if submission is None or judge is None:
        raise FileNotFoundError(f"{run_dir} has no submission.json/judge.json; judge it first")

    card = load_card(submission["task_id"])
    vault, _ = load_vault(submission["task_id"])
    rubric = {item.id: item for item in vault.rubric}
    events = _events(run_dir)
    candidates = _read(run_dir / "all_candidates.json") or []
    fates = _family_fates(events, candidates)
    stats = submission.get("stats", {})
    usage = submission.get("usage", {})

    lines = [
        HEADER, "---",
        f"run_id: {submission['run_id']}",
        f"task: {submission['task_id']}",
        f"domain: {card.domain}",
        f"system: {submission['system']}",
        f"seed: {submission['seed']}",
        f"llm: {submission.get('config', {}).get('llm', '?')}",
        f"isolation: {submission.get('isolation', '?')}",
        f"usd: {usage.get('usd', 0):.4f}",
        f"generated: {datetime.now(UTC).isoformat(timespec='seconds')}",
        "---", "",
        f"# {submission['task_id']} / {submission['system']} (seed {submission['seed']})", "",
        "## Outcome", "",
        f"- claim reproduced: **{judge['claim_reproduced']}**",
        (f"- method match: **{judge['method_match']:.2f}** "
        f"(recovered: {judge['method_recovered']}, "
        f"recovered in top 3: {judge.get('any_method_recovered')})"),
        f"- valid alternative: {judge['valid_alternative']}",
        f"- structural similarity to the reference: {judge['structural_similarity']:.2f}",
        f"- paper's method family: `{judge.get('reference_family', '?')}`",
        f"- submitted family: `{next((c['family'] for c in judge.get('all_candidates', [])), '?')}`",
        (f"- spend: ${usage.get('usd', 0):.4f} over {usage.get('calls', 0)} model calls, "
        f"{usage.get('wall_seconds', 0)}s wall clock"),
        "",
    ]

    lines += ["## Which parts of the paper's method came back", "",
              "| component | weight | judges | recovered |", "|---|---|---|---|"]
    for item_id, scores in judge.get("rubric_scores", {}).items():
        item = rubric.get(item_id)
        model_scores = [v for k, v in scores.items() if k != "lexical"]
        mean = sum(model_scores) / len(model_scores) if model_scores else 0.0
        mark = {1.0: "yes", 0.0: "no"}.get(mean, "partial")
        text = item.text if item else item_id
        lines.append(f"| {item_id}: {text} | {item.weight if item else '?'} | "
                     f"{json.dumps(model_scores)} | {mark} |")
    lines.append("")

    if fates:
        lines += ["## Method families the run explored", "",
                  "| family | candidates | best gap | reached submission | notes |",
                  "|---|---|---|---|---|"]
        for name, f in sorted(fates.items(), key=lambda kv: kv[1]["best_gap"]):
            note = "; ".join(dict.fromkeys(f["diagnoses"]))[:120]
            lines.append(f"| `{name}` | {f['candidates']} | {f['best_gap']:.3f} | "
                         f"{'yes' if f['ready'] else 'no'} | {note} |")
        lines.append("")

    pressure = []
    if stats.get("deaths"):
        pressure.append(f"- agent deaths: {stats['deaths']}, respawns: {stats.get('respawns', 0)}")
    if stats.get("colony_deaths"):
        pressure.append(f"- colony deaths: {stats['colony_deaths']}, "
                        f"foundings: {stats.get('foundings', 0)}")
        for death in (stats.get("colony_lineage") or [])[:5]:
            pressure.append(f"  - `{death['colony']}` died at round {death['round']} "
                            f"({death['cause']}), best gap {death['best_gap']}")
    if pressure:
        lines += ["## Survival pressure", "", *pressure, ""]

    if judge.get("loopholes"):
        lines += ["## Loopholes flagged", "", *[f"- {x}" for x in judge["loopholes"]], ""]
    if judge.get("human_review"):
        lines += ["## Needs human review", "", *[f"- {x}" for x in judge["human_review"]], ""]

    out_dir = skills.learnings_dir(card.domain)
    stamp = datetime.now(UTC).strftime("%Y%m%d")
    path = out_dir / f"{stamp}-{submission['task_id']}-{submission['system']}-s{submission['seed']}.md"
    path.write_text("\n".join(lines) + "\n")
    reindex(card.domain)
    return path


def _frontmatter(path: Path) -> dict[str, str]:
    meta, inside = {}, False
    for line in path.read_text().splitlines():
        if line.strip() == "---":
            if inside:
                break
            inside = True
            continue
        if inside and ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta


def reindex(domain: str) -> Path:
    """Rebuild a domain's INDEX.md: one row per artifact, plus what agents keep missing."""
    out_dir = skills.learnings_dir(domain)
    artifacts = sorted(p for p in out_dir.glob("*.md") if p.name != "INDEX.md")
    rows, missed, seen_runs = [], defaultdict(lambda: [0, 0]), 0
    for path in artifacts:
        meta = _frontmatter(path)
        body = path.read_text()
        rows.append((meta.get("generated", "")[:10], meta.get("task", "?"),
                     meta.get("system", "?"), meta.get("seed", "?"), meta.get("llm", "?"),
                     path.name))
        for line in body.splitlines():
            if line.startswith("| r") and line.count("|") >= 5:
                parts = [c.strip() for c in line.strip("|").split("|")]
                item = parts[0].split(":")[0]
                missed[item][1] += 1
                if parts[-1] == "yes":
                    missed[item][0] += 1
        seen_runs += 1

    lines = [HEADER, f"# {domain}: learnings", "",
             (f"{seen_runs} judged run(s) distilled into this directory. Artifacts are "
             "evaluator-side: they quote the sealed rubric and must not be shown to agents."),
             ""]
    if rows:
        lines += ["## Runs", "", "| date | task | system | seed | llm | artifact |",
                  "|---|---|---|---|---|---|"]
        lines += [f"| {d} | {t} | {s} | {sd} | {m} | [{n}]({n}) |" for d, t, s, sd, m, n in rows]
        lines.append("")
    if missed:
        lines += ["## Method components by recovery rate", "",
                  ("Low rates are the finding: a component agents rarely infer from the "
                  "abstract alone."), "", "| component | recovered | runs | rate |",
                  "|---|---|---|---|"]
        for item, (hit, total) in sorted(missed.items(), key=lambda kv: kv[1][0] / max(1, kv[1][1])):
            lines.append(f"| {item} | {hit} | {total} | {hit / max(1, total):.0%} |")
        lines.append("")

    path = out_dir / "INDEX.md"
    path.write_text("\n".join(lines) + "\n")
    return path


def distill_all(runs_dir: str | Path) -> list[Path]:
    out = []
    for judge_file in sorted(Path(runs_dir).rglob("judge.json")):
        if "latest" not in judge_file.parts:
            out.append(distill(judge_file.parent))
    return out
